import { z } from 'zod'

import { isIsoDate } from '../delivery/calendar'
import { isValidPostcode, normalizePostcode } from '../delivery/constants'

import { cartKind } from '../vouchers/cart'

import { MAX_LINE_QUANTITY, MAX_ORDER_LINES } from './constants'
import { isValidEmail, normalizeDic, normalizeIco, normalizePhone } from './validators'

/**
 * The checkout request (`POST /api/checkout/place-order`) – THE validation contract between the
 * browser and the server. The server parses every request with `parseCheckoutInput()`; the
 * browser uses the same function for inline messages before sending.
 *
 * Deliberately NOT part of the input: any price, total, VAT, delivery price or product name.
 * The server re-reads everything from the database (unknown keys are dropped by zod).
 */

const text = (max: number) => z.string().trim().max(max, `Nejvýše ${max} znaků.`)
const required = (max: number, message: string) => text(max).min(1, message)

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max, `Nejvýše ${max} znaků.`)
    .optional()
    .transform((value) => value || undefined)

const postcode = z
  .string()
  .trim()
  .transform((value) => normalizePostcode(value))
  .refine((value) => isValidPostcode(value), 'Zadejte PSČ jako pět číslic, např. 120 00.')

export const cartLineInputSchema = z.object({
  productId: z.number().int().positive(),
  variantId: z.string().max(64).nullable(),
  quantity: z.number().int().min(1).max(MAX_LINE_QUANTITY),
})
export type CartLineInput = z.infer<typeof cartLineInputSchema>

const attributionValue = z.string().trim().max(500).optional()

export const attributionSchema = z
  .object({
    utmSource: attributionValue,
    utmMedium: attributionValue,
    utmCampaign: attributionValue,
    utmTerm: attributionValue,
    utmContent: attributionValue,
    gclid: attributionValue,
    fbclid: attributionValue,
    referrer: attributionValue,
    landingPage: attributionValue,
    firstSeenAt: attributionValue,
  })
  .partial()

export const checkoutInputSchema = z.object({
  /** Random id generated by the browser for this checkout: makes the submit idempotent. */
  checkoutId: z.uuid('Neplatný identifikátor objednávky. Obnovte prosím stránku.'),
  /** Signed render time of the checkout page (timing trap), see `formToken.ts`. */
  formToken: z.string().max(200),
  /** Honeypot: hidden field, people leave it empty. */
  website: z.string().max(200).optional(),
  turnstileToken: z.string().max(4096).optional(),
  lines: z
    .array(cartLineInputSchema)
    .min(1, 'Košík je prázdný.')
    .max(MAX_ORDER_LINES, 'V košíku je příliš mnoho položek.'),
  /**
   * Required for goods (checked in `parseCheckoutInput`); absent for a cart with only ELECTRONIC
   * vouchers (stage 7: no shipping, no date).
   */
  delivery: z
    .object({
      postcode,
      methodId: z.number({ error: 'Vyberte způsob dopravy.' }).int().positive(),
      date: z.string().refine((value) => isIsoDate(value), 'Vyberte termín.'),
    })
    .optional(),
  customer: z.object({
    firstName: required(100, 'Vyplňte jméno.'),
    lastName: required(100, 'Vyplňte příjmení.'),
    email: text(254)
      .min(1, 'Vyplňte e-mail.')
      .refine(isValidEmail, 'Zadejte e-mail ve tvaru jmeno@domena.cz.')
      .transform((value) => value.toLowerCase()),
    phone: text(40)
      .min(1, 'Vyplňte telefon.')
      .refine(
        (value) => normalizePhone(value) !== null,
        'Zadejte telefon jako devět číslic, např. 602 123 456 (případně s +420).',
      )
      .transform((value) => normalizePhone(value) as string),
    companyName: optionalText(200),
    ico: optionalText(20)
      .refine(
        (value) => !value || normalizeIco(value) !== null,
        'IČO má 8 číslic – zkontrolujte ho.',
      )
      .transform((value) => (value ? (normalizeIco(value) ?? undefined) : undefined)),
    dic: optionalText(20)
      .refine((value) => !value || normalizeDic(value) !== null, 'DIČ zadejte ve tvaru CZ12345678.')
      .transform((value) => (value ? (normalizeDic(value) ?? undefined) : undefined)),
  }),
  /** Delivery address – required for delivery methods (checked with `addressSchema`). */
  address: z
    .object({
      street: text(200),
      city: text(100),
      postcode: z.string().trim().max(10),
    })
    .optional(),
  note: optionalText(1000),
  voucherCode: optionalText(100),
  /** Stage 7: optional name + message printed on the bought vouchers. */
  voucherDetails: z
    .object({
      recipientName: optionalText(60),
      message: optionalText(160),
    })
    .optional(),
  consents: z.object({
    terms: z.literal(true, {
      error: 'Pro odeslání objednávky potřebujeme váš souhlas s obchodními podmínkami.',
    }),
    newsletter: z.boolean().default(false),
    heurekaOptOut: z.boolean().default(false),
  }),
  attribution: attributionSchema.optional(),
  /** Estimated total the customer saw; when the server computes another one it asks again. */
  expectedTotal: z.number().int().nonnegative().optional(),
})

export type CheckoutInput = z.infer<typeof checkoutInputSchema>
export type CheckoutRawInput = z.input<typeof checkoutInputSchema>

/** Delivery address, required for own delivery and courier. */
export const addressSchema = z.object({
  street: required(200, 'Vyplňte ulici a číslo domu.').refine(
    (value) => /\d/.test(value),
    'Doplňte číslo domu.',
  ),
  city: required(100, 'Vyplňte obec.'),
  postcode,
})
export type AddressInput = z.infer<typeof addressSchema>

/** Field path ("customer.email") → first Czech message. */
export type FieldErrors = Record<string, string>

export function issuesToFieldErrors(issues: z.core.$ZodIssue[]): FieldErrors {
  const errors: FieldErrors = {}
  for (const issue of issues) {
    const key = issue.path.map(String).join('.') || '_form'
    if (!errors[key]) errors[key] = issue.message
  }
  return errors
}

export type ParseResult =
  | { ok: true; data: CheckoutInput; address: AddressInput | null }
  | { ok: false; errors: FieldErrors }

/**
 * Validates the whole checkout input. `needsAddress` = the chosen method delivers to an address;
 * the address postcode must then be the postcode the delivery options were computed for.
 */
export function parseCheckoutInput(raw: unknown, needsAddress: boolean): ParseResult {
  const parsed = checkoutInputSchema.safeParse(raw)
  const errors: FieldErrors = parsed.success ? {} : issuesToFieldErrors(parsed.error.issues)
  // Mixed carts (electronic voucher + goods) are refused by the server with their own message.
  if (parsed.success && !parsed.data.delivery && cartKind(parsed.data.lines) === 'goods') {
    errors['delivery.methodId'] = 'Vyberte způsob dopravy a termín (v košíku).'
  }

  let address: AddressInput | null = null
  if (needsAddress) {
    const rawAddress = (raw as { address?: unknown } | null)?.address ?? {}
    const addressResult = addressSchema.safeParse(rawAddress)
    if (!addressResult.success) {
      for (const [key, message] of Object.entries(
        issuesToFieldErrors(addressResult.error.issues),
      )) {
        errors[`address.${key}`] ??= message
      }
    } else {
      address = addressResult.data
      const deliveryPostcode = parsed.success
        ? parsed.data.delivery?.postcode
        : normalizePostcode(
            String((raw as { delivery?: { postcode?: unknown } })?.delivery?.postcode ?? ''),
          )
      if (address.postcode !== deliveryPostcode) {
        errors['address.postcode'] ??=
          'PSČ adresy se liší od PSČ, pro které jste vybrali dopravu. Vyberte prosím dopravu znovu.'
      }
    }
  }

  if (!parsed.success || Object.keys(errors).length > 0) return { ok: false, errors }
  return { ok: true, data: parsed.data, address }
}
